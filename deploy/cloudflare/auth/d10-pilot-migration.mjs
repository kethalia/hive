// Dedicated-database migration pilot; all authority/deployment receipts here are
// local fixtures. Never use this entry as installed delivery authority.
import { randomUUID } from "node:crypto";
import { readFile, rename, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

export async function runPilotMigration({
  repository,
  ownerFile,
  appDigests,
  checkpointFile,
  sourceSha,
}) {
  if (!/^[a-f0-9]{40}$/.test(sourceSha ?? "")) throw Error("pilot_source_unpinned");
  const root = resolve(repository),
    require = createRequire(joinPath(root, "services/migrate/package.json")),
    pg = require("pg");
  const u = new URL((await readFile(ownerFile, "utf8")).trim());
  if (u.pathname !== "/hive_d10_pilot" || !u.hostname.endsWith(".aws.neon.tech"))
    throw Error("pilot_database_scope");
  u.hostname = u.hostname.replace("-pooler.", ".");
  const url = u.toString(),
    modules = (name) =>
      import(pathToFileURL(joinPath(root, `services/migrate/src/delivery/${name}.mjs`)).href);
  const [
    { digest, validatePlan, validateScope },
    { createMigrationDatabase },
    { createDeliveryMigrationController },
    { advanceDatabaseChange },
  ] = await Promise.all([
    modules("contracts"),
    modules("postgres"),
    modules("runner"),
    modules("job"),
  ]);
  const client = new pg.Client({ connectionString: url, connectionTimeoutMillis: 5000 });
  await client.connect();
  try {
    let saved;
    try {
      saved = JSON.parse(await readFile(checkpointFile, "utf8"));
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    let scope, plan, runId;
    if (saved) {
      if (
        saved.host !== u.hostname ||
        saved.database !== "hive_d10_pilot" ||
        saved.appDigests?.join() !== appDigests.join() ||
        saved.sourceSha !== sourceSha
      )
        throw Error("pilot_checkpoint_scope_changed");
      scope = validateScope(saved.scope);
      plan = validatePlan(saved.plan);
      runId = saved.runId;
    } else {
      const existing = await client.query(
        "SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='delivery_tasks' AND column_name='d10_pilot_seq'",
      );
      if (existing.rowCount) throw Error("pilot_migration_already_present");
      const schemaSql = `SELECT jsonb_build_object(
        'columns',(SELECT coalesce(jsonb_agg(jsonb_build_object('name',a.attname,'type',format_type(a.atttypid,a.atttypmod),'notnull',a.attnotnull,'identity',a.attidentity,'default',pg_get_expr(d.adbin,d.adrelid)) ORDER BY a.attname),'[]'::jsonb) FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE a.attrelid='public.delivery_tasks'::regclass AND a.attname IN ('d10_pilot_seq','d10_pilot_marker') AND a.attnum>0 AND NOT a.attisdropped),
        'triggers',(SELECT coalesce(jsonb_agg(pg_get_triggerdef(t.oid) ORDER BY t.tgname),'[]'::jsonb) FROM pg_trigger t WHERE t.tgrelid='public.delivery_tasks'::regclass AND t.tgname='d10_pilot_dualwrite' AND NOT t.tgisinternal),
        'functions',(SELECT coalesce(jsonb_agg(pg_get_functiondef(p.oid) ORDER BY p.oid),'[]'::jsonb) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.proname='d10_pilot_dualwrite'),
        'indexes',(SELECT coalesce(jsonb_agg(pg_get_indexdef(i.indexrelid) ORDER BY i.indexrelid),'[]'::jsonb) FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname='d10_pilot_seq_idx')
      ) AS schema`;
      const expandSql = [
        "ALTER TABLE public.delivery_tasks ADD COLUMN d10_pilot_seq bigint GENERATED BY DEFAULT AS IDENTITY, ADD COLUMN d10_pilot_marker text",
        "CREATE UNIQUE INDEX d10_pilot_seq_idx ON public.delivery_tasks(d10_pilot_seq)",
        "CREATE FUNCTION public.d10_pilot_dualwrite() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.d10_pilot_marker=coalesce(NEW.d10_pilot_marker,'ready'); RETURN NEW; END $$",
        "CREATE TRIGGER d10_pilot_dualwrite BEFORE INSERT OR UPDATE ON public.delivery_tasks FOR EACH ROW EXECUTE FUNCTION public.d10_pilot_dualwrite()",
      ];
      const before = digest((await client.query(schemaSql)).rows);
      let after;
      await client.query("BEGIN");
      try {
        for (const sql of expandSql) await client.query(sql);
        after = digest((await client.query(schemaSql)).rows);
      } finally {
        await client.query("ROLLBACK");
      }
      scope = {
        ownerId: randomUUID(),
        repositoryId: "1",
        environmentKey: "isolated-neon-d10-pilot",
        targetId: randomUUID(),
        databaseName: "hive_d10_pilot",
      };
      plan = {
        schemaVersion: 1,
        id: randomUUID(),
        sourceSha,
        oldAppDigest: appDigests[0],
        newAppDigest: appDigests[1],
        compatibilityDigest: digest({ scenario: "local-workerd-pause-v1" }),
        beforeSchemaDigest: before,
        afterSchemaDigest: after,
        batchSize: 2,
        statementTimeoutMs: 5000,
        lockTimeoutMs: 1000,
        schemaSql,
        expandSql,
        highWaterSql:
          "SELECT coalesce(max(d10_pilot_seq),0)::text AS high_water FROM public.delivery_tasks",
        batchSql:
          "WITH chosen AS (SELECT id FROM public.delivery_tasks WHERE d10_pilot_seq>$1::bigint AND d10_pilot_seq<=$2::bigint ORDER BY d10_pilot_seq LIMIT $3::integer FOR UPDATE), changed AS (UPDATE public.delivery_tasks t SET d10_pilot_marker='ready' FROM chosen WHERE t.id=chosen.id RETURNING t.d10_pilot_seq) SELECT d10_pilot_seq::text AS key FROM changed ORDER BY d10_pilot_seq",
        integritySql:
          "SELECT count(*) FILTER (WHERE d10_pilot_marker IS DISTINCT FROM 'ready')::text AS violations,count(*)::text AS total_rows FROM public.delivery_tasks",
        integrityTables: [{ schema: "public", name: "delivery_tasks" }],
      };
      runId = randomUUID();
      await writeFile(
        checkpointFile,
        JSON.stringify({
          host: u.hostname,
          database: "hive_d10_pilot",
          appDigests,
          sourceSha,
          scope,
          plan,
          runId,
        }),
        { mode: 0o600, flag: "wx" },
      );
    }
    const ledger = await client.query(
      "SELECT to_regnamespace('hive_delivery_db') IS NOT NULL AS present",
    );
    if (!ledger.rows[0].present)
      await client.query(
        await readFile(joinPath(root, "services/migrate/src/delivery/ledger.sql"), "utf8"),
      );
    const planDigest = digest(plan),
      scopeDigest = digest(scope);
    let armed = false,
      calls = 0,
      notifyBlocked,
      releaseBlocked;
    const blocked = new Promise((resolve) => {
      notifyBlocked = resolve;
    });
    const resume = new Promise((resolve) => {
      releaseBlocked = resolve;
    });
    const options = {
      enabled: true,
      db: createMigrationDatabase(url),
      scope,
      plan,
      expectedPlanDigest: planDigest,
      authorize: async ({ action, tx }) => {
        if (armed && action === "backfill" && ++calls === 2) {
          await tx.$executeRawUnsafe(
            "SELECT set_config('application_name','hive-d10-pilot-interruption',true)",
          );
          const [identity] = await tx.$queryRawUnsafe(
            "SELECT pid,backend_start::text AS started FROM pg_stat_activity WHERE pid=pg_backend_pid()",
          );
          notifyBlocked(identity);
          await resume;
        }
        return {
          scopeDigest,
          planDigest,
          runId,
          action,
          expiresAt: Date.now() + 20000,
          authorityDigest: digest({ fixture: "local-pilot", action }),
        };
      },
      observeDeployment: async ({ expected }) => ({
        ...expected,
        observedAt: Date.now() - 1,
        expiresAt: Date.now() + 20000,
        receiptDigest: digest(expected),
      }),
    };
    let controller = createDeliveryMigrationController(options);
    let state = await controller.begin(runId);
    if (state.phase === "pending") state = await controller.tick(runId, "expand");
    if (state.phase === "expanded") state = await controller.tick(runId, "compatible");
    if (!["compatible", "backfilled", "verified"].includes(state.phase))
      throw Error("pilot_checkpoint_expected");
    await client.query(
      "GRANT USAGE, SELECT ON SEQUENCE public.delivery_tasks_d10_pilot_seq_seq TO hive_app_runtime",
    );
    let interruptionVerified = Boolean(saved?.interruptionVerified);
    if (!interruptionVerified && state.phase === "compatible") {
      const before = await controller.read(runId);
      armed = true;
      const cancellation = new AbortController();
      const pending = controller.tick(runId, "backfill", { signal: cancellation.signal });
      let timer, identity;
      try {
        identity = await Promise.race([
          blocked,
          pending.then(() => {
            throw Error("pilot_interruption_not_reached");
          }),
          new Promise((_resolve, reject) => {
            timer = setTimeout(() => reject(Error("pilot_interruption_timeout")), 8000);
          }),
        ]);
      } catch (error) {
        cancellation.abort();
        releaseBlocked();
        await pending.catch(() => {});
        throw error;
      } finally {
        clearTimeout(timer);
      }
      try {
        const killed = await client.query(
          "SELECT pg_terminate_backend(pid) AS killed FROM pg_stat_activity WHERE pid=$1 AND backend_start=$2::timestamptz AND datname='hive_d10_pilot' AND application_name='hive-d10-pilot-interruption'",
          [identity.pid, identity.started],
        );
        if (killed.rows.length !== 1 || killed.rows[0].killed !== true)
          throw Error("pilot_interruption_identity_changed");
      } finally {
        releaseBlocked();
      }
      let rejected = false;
      try {
        await pending;
      } catch {
        rejected = true;
      }
      if (!rejected) throw Error("pilot_interruption_not_rolled_back");
      armed = false;
      controller = createDeliveryMigrationController(options);
      const after = await controller.read(runId);
      if (
        before.cursor !== after.cursor ||
        before.changedRows !== after.changedRows ||
        before.checkpointDigest !== after.checkpointDigest
      )
        throw Error("pilot_interruption_checkpoint_changed");
      interruptionVerified = true;
      const checkpoint = JSON.parse(await readFile(checkpointFile, "utf8"));
      checkpoint.interruptionVerified = true;
      const nextFile = `${checkpointFile}.${randomUUID()}.tmp`;
      await writeFile(nextFile, JSON.stringify(checkpoint), { mode: 0o600, flag: "wx" });
      await rename(nextFile, checkpointFile);
    }
    if (!interruptionVerified) throw Error("pilot_interruption_evidence_missing");
    const next = await advanceDatabaseChange({
      controller,
      runId,
      maxTicks: 64,
      maxDurationMs: 50000,
    });
    if (next.phase !== "activation_ready" || next.state.phase !== "verified")
      throw Error("pilot_integrity_failed");
    return {
      runId,
      planDigest,
      checkpointDigest: next.state.checkpointDigest,
      phase: next.phase,
      interruptionVerified,
      contractAuthorized: false,
    };
  } finally {
    await client.end();
  }
}
function joinPath(root, path) {
  return resolve(root, path);
}

export async function verifyPilotInvariant({ repository, ownerFile, taskId }) {
  const require = createRequire(joinPath(resolve(repository), "services/migrate/package.json")),
    pg = require("pg");
  const u = new URL((await readFile(ownerFile, "utf8")).trim());
  if (u.pathname !== "/hive_d10_pilot" || !u.hostname.endsWith(".aws.neon.tech"))
    throw Error("pilot_database_scope");
  u.hostname = u.hostname.replace("-pooler.", ".");
  const client = new pg.Client({ connectionString: u.toString(), connectionTimeoutMillis: 5000 });
  await client.connect();
  try {
    const result = await client.query(
      "SELECT count(*) FILTER (WHERE d10_pilot_marker IS DISTINCT FROM 'ready')::int AS violations, count(*) FILTER (WHERE id=$1::uuid AND d10_pilot_marker='ready')::int AS task_ok FROM public.delivery_tasks",
      [taskId],
    );
    if (result.rows[0].violations !== 0 || result.rows[0].task_ok !== 1)
      throw Error("pilot_postwrite_integrity_failed");
    return true;
  } finally {
    await client.end();
  }
}
